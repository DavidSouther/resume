#!/usr/bin/env bash
# Runs inside the dev container, as root on Linux, started by scripts/psstat-answers.sh through
# ./linux. Runs ../psstat/questions.sh in a bcdocker container and writes ANSWERS.md from its
# traces. Needs containers/psstat, a root built from ../psstat/Dockerfile (./linux builds it).
#
# Writes ANSWERS.md, run.log, and traces/ here. It never touches ../psstat/ANSWERS.md.

set -euo pipefail
cd "$(dirname "$0")/.."

[[ $(id -u) == 0 ]] || { echo "psstat-run: needs root" >&2; exit 1; }
[[ -d containers/psstat ]] || { echo "psstat-run: no containers/psstat; run scripts/psstat-answers.sh" >&2; exit 1; }

cargo build

# Refresh the container's copy of psstat so edits to psstat.sh are traced.
rm -rf containers/psstat/psstat
cp -a ../psstat containers/psstat/psstat
rm -rf containers/psstat/psstat/traces
mkdir containers/psstat/psstat/traces

# questions.sh has no shebang, so sh runs it. It exits with the status of its last command; its output is the record.
target/debug/bcdocker run psstat /bin/sh /psstat/questions.sh </dev/null 2>&1 | tee run.log || true

rm -rf traces
cp -a containers/psstat/psstat/traces traces

# Count reads of /proc files in an strace -f trace, as a total on the first line and then one
# line per path. A read counts when its descriptor was opened by an openat of a /proc path in
# the same process and not closed since. Unfinished and resumed openat lines are paired by
# process.
count_proc_reads() {
  awk '
    /openat\(.*"\/proc/ && /<unfinished/ {
      match($0, /"[^"]*"/); pending[$1] = substr($0, RSTART + 1, RLENGTH - 2); next }
    /openat\(.*"\/proc/ && /= [0-9]+/ {
      match($0, /"[^"]*"/); p = substr($0, RSTART + 1, RLENGTH - 2)
      fd[$1, $NF] = p; next }
    /openat resumed/ && ($1 in pending) && /= [0-9]+$/ {
      fd[$1, $NF] = pending[$1]; delete pending[$1]; next }
    /close\([0-9]+\)/ { match($0, /close\([0-9]+/); delete fd[$1, substr($0, RSTART + 6, RLENGTH - 6)]; next }
    / read\([0-9]+/ { match($0, /read\([0-9]+/); n = substr($0, RSTART + 5, RLENGTH - 5)
      if (($1, n) in fd) { reads++; by[fd[$1, n]]++ } }
    END { print reads + 0; for (p in by) print "  " by[p] "  " p }
  ' "$1"
}

question() { grep '^> ' ../psstat/ANSWERS.md | sed -n "$1p"; }
fence() { printf '```\n%s\n```\n' "$1"; }

short_report=$(count_proc_reads traces/list-short)
short_reads=$(head -n 1 <<<"$short_report")
short_dents=$(grep -c 'getdents' traces/list-short || true)

{
  echo "# psstat answers from bcdocker"
  echo
  echo "Generated by \`scripts/psstat-run.sh\` on $(date -u +%Y-%m-%d) from \`run.log\` and \`traces/\`."
  echo "The experiment ran \`../psstat/questions.sh\` as the application of a \`bcdocker run psstat\` container, so PID 1 is \`bcdocker\` and the application is PID 2."
  echo "Kernel: \`$(head -n 1 run.log)\`"
  echo
  echo "## 1. The read syscall count"
  echo
  question 1
  echo
  echo "In \`traces/list-short\`, read(2) ran $short_reads time(s) on a descriptor opened under \`/proc\`, and \`getdents\` ran $short_dents time(s) to list the \`/proc\` directory. Reads by path (bash itself reads \`/proc/filesystems\` when it starts; the script's own reads of \`/proc/<pid>/\` files would appear here too):"
  echo
  fence "$(tail -n +2 <<<"$short_report")"
  echo
  fence "$(grep -E 'openat.*/proc|getdents|read\(' traces/list-short | head -n 40)"
  echo
  echo "## 2. Break it on purpose"
  echo
  question 2
  echo
  echo "Output of \`su nobody\` running \`--list-pid-is 1\` then \`cat /proc/1/environ\`, from \`run.log\`:"
  echo
  fence "$(grep -A12 '^0$' run.log | tail -n 14)"
  echo
  echo "## 4. PIDs are not contiguous"
  echo
  question 4
  echo
  echo "PIDs listed by \`--list-short\` in this container:"
  echo
  fence "$(awk '/^PID$/{f=1;next} f&&/^[0-9]+$/{printf "%s ", $0} f&&!/^[0-9]+$/{exit}' run.log)"
  echo
  echo "## 6. Compare with ps"
  echo
  question 6
  echo
  echo "\`ps -eo pid,stat,comm,args\` followed by \`./psstat.sh --list-long\`, from \`run.log\`:"
  echo
  fence "$(sed -n '/PID *STAT/,/^PID CMD ST/p' run.log; sed -n '/^PID CMD ST CMD_ARGS/,/^PID/p' run.log | head -n 20)"
  echo
  echo "## 7. The scheduling policy mapping"
  echo
  question 7
  echo
  echo "\`--list-sched-policy-is 0\` traced in \`traces/list-shed-policy\`; \`/proc\` files it opened:"
  echo
  fence "$(grep -E 'openat.*/proc/[0-9]+/(stat|comm|cmdline)' traces/list-shed-policy | awk '{$1=""; print}' | sort | uniq -c | sort -rn | head -n 12)"
  echo
  echo "## 8. Reproduce a failure"
  echo
  question 8
  echo
  echo "\`./psstat.sh --list-pid-is -10\`, from \`run.log\`:"
  echo
  fence "$(grep -B1 -A3 'No such file' run.log | head -n 8)"
} >ANSWERS.md

echo "wrote $PWD/ANSWERS.md, run.log, traces/"
